export function getProductBadge(product: Product): { label: string; type: string } | null {
  if (product.originalPrice && product.originalPrice > product.price) {
    const pct = Math.round(((product.originalPrice - product.price) / product.originalPrice) * 100);
    return { label: `${pct}% OFF`, type: 'sale' };
  }
  if (product.badge) {
    const map: Record<string, string> = {
      'Best Seller': 'bestseller',
      'New Arrival': 'new',
      'Trending': 'trending',
    };
    return { label: product.badge, type: map[product.badge] || 'default' };
  }
  return null;
}

export const getProductById = (id: number): Product | undefined =>
  getAllProducts().find((p) => p.id === id);

export const getProductsByCategory = (category: string): Product[] =>
  getAllProducts().filter((p) => p.category === category);

export const getFeaturedProducts = (): Product[] =>
  getAllProducts().filter((p) => p.featured);

export const getRelatedProducts = (product: Product, count = 4): Product[] =>
  getAllProducts()
    .filter((p) => p.category === product.category && p.id !== product.id)
    .slice(0, count);

export const searchProducts = (query: string): Product[] => {
  const q = query.toLowerCase();
  return getAllProducts().filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.description.toLowerCase().includes(q) ||
      p.category.toLowerCase().includes(q)
  );
};

export const sortProducts = (items: Product[], sort: string): Product[] => {
  const sorted = [...items];
  switch (sort) {
    case 'price-asc':
      return sorted.sort((a, b) => a.price - b.price);
    case 'price-desc':
      return sorted.sort((a, b) => b.price - a.price);
    case 'name-asc':
      return sorted.sort((a, b) => a.name.localeCompare(b.name));
    case 'name-desc':
      return sorted.sort((a, b) => b.name.localeCompare(a.name));
    case 'rating':
      return sorted.sort((a, b) => b.rating - a.rating);
    case 'newest':
      return sorted.sort((a, b) => b.id - a.id);
    case 'popular':
      return sorted.sort((a, b) => b.reviews - a.reviews);
    default:
      return sorted;
  }
};